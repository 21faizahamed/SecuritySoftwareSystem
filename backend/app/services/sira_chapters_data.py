    """Create an Other Security System / Guarding / Connectivity / Physical Barrier requirement entry."""
    return {
        "section_type": "OTHER_SECURITY_SYSTEM",
        "requirement_type": "OTHER_SYSTEM",
        "equipment_code": eq_code,
        "location_name": "Establishment-Wide / Specified Area",
        "view_code": None,
        "title": req_name,
        "original_text": f"{req_name}: {details}",
        "plain_summary": f"{req_name} — {details}",
        "remarks": details,
        "obligation_level": obligation,
        "pdf_page": page,
        "table_ref": table_name,
        "condition": condition,
        "standard_codes": standards or ["STD-P2-C2-01"],
    }


